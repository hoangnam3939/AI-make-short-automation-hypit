const i18n = (() => {
  let current = localStorage.getItem("ui_lang") || "vi";

  function t(key) {
    return (TRANSLATIONS[current] && TRANSLATIONS[current][key]) || TRANSLATIONS.vi[key] || key;
  }

  function apply(code) {
    if (!TRANSLATIONS[code]) return; // ngôn ngữ chưa có bản dịch thật — không đổi gì cả, không giả vờ
    current = code;
    localStorage.setItem("ui_lang", code);
    document.documentElement.lang = code;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
      el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
    });
    document.dispatchEvent(new CustomEvent("i18n-changed", { detail: { code } }));
  }

  return { t, apply, get current() { return current; }, languages: LANGUAGES };
})();
